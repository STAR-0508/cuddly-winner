// 计算农历（使用 lunar-javascript）
function computeLunar() {
  try {
    if (typeof Lunar === 'undefined') {
      return { error: '农历库未加载' };
    }
    const solar = Solar.fromDate(new Date());
    const lunar = solar.getLunar();

    const data = {
      lunarDate: lunar.toString().split('年')[1] || lunar.toString(),
      yearInGanZhi: lunar.getYearInGanZhi(),
      zodiac: lunar.getYearShengXiao(),
      monthInChinese: lunar.getMonthInChinese(),
      dayInChinese: lunar.getDayInChinese(),
      festival: lunar.getFestival(),
      term: lunar.getJieQi(),
    };
    return data;
  } catch (e) {
    return { error: e.message };
  }
}

// 渲染天气
function renderWeather(data) {
  const box = $('weatherBox');
  if (!data || data.error) {
    box.innerHTML = `<div class="di-error">天气获取失败</div>`;
    return;
  }
  const cur = data.current_condition?.[0];
  const loc = data.nearest_area?.[0];
  if (!cur) { box.innerHTML = `<div class="di-error">数据异常</div>`; return; }

  const descZh = cur.lang_zh?.[0]?.value || cur.weatherDesc?.[0]?.value || '';
  const temp = cur.temp_C;
  const feels = cur.FeelsLikeC;
  const humidity = cur.humidity;
  const wind = cur.windspeedKmph;
  const city = loc?.areaName?.[0]?.value || '未知';
  const region = loc?.region?.[0]?.value || '';

  box.innerHTML = `
    <div class="weather-loc">📍 ${region ? region + ' · ' : ''}${city}</div>
    <div class="weather-temp">${temp}°</div>
    <div class="weather-desc">${descZh}</div>
    <div class="weather-meta">
      <span>🤒 ${feels}°C</span>
      <span>💧 ${humidity}%</span>
      <span>💨 ${wind} km/h</span>
    </div>
  `;
}

// 渲染农历
function renderLunar(data) {
  const box = $('lunarBox');
  if (!data || data.error) {
    box.innerHTML = `<div class="di-error">${data?.error || '农历计算失败'}</div>`;
    return;
  }
  const parts = [];
  parts.push(`<div class="lunar-main">${data.monthInChinese}月${data.dayInChinese}</div>`);
  parts.push(`<div class="lunar-sub">${data.yearInGanZhi}年 · ${data.zodiac}</div>`);
  if (data.festival) {
    parts.push(`<span class="lunar-festival">🎊 ${data.festival}</span>`);
  }
  if (data.term) {
    parts.push(`<span class="lunar-solar-term">🌿 ${data.term}</span>`);
  }
  box.innerHTML = parts.join('');
}

// 渲染历史
function renderHistory() {
  const box = $('historyBox');
  const now = new Date();
  const key = `${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`;
  const events = HISTORY_DATA[key] || [];

  if (events.length === 0) {
    box.innerHTML = `<div class="di-error">暂无数据</div>`;
    return;
  }

  const html = events.slice(0, 4).map(([year, text]) =>
    `<li><span class="history-year">${year}</span><span class="history-text">${text}</span></li>`
  ).join('');
  box.innerHTML = `<ul class="history-list">${html}</ul>`;
}

// 渲染每日一言
function renderHitokoto(data) {
  const box = $('hitokotoBox');
  if (!data || !data.hitokoto) {
    box.innerHTML = `<div class="di-error">获取失败，请🔄重试</div>`;
    return;
  }
  let from = '';
  if (data.from) from += `《${data.from}》`;
  if (data.from_who) from += ` —— ${data.from_who}`;

  box.innerHTML = `
    <div class="hitokoto-text">「${data.hitokoto}」</div>
    <div class="hitokoto-from">${from || '—— 佚名'}</div>
  `;
}

// 获取天气（带 fallback）
async function fetchWeather() {
  try {
    const resp = await fetch('https://wttr.in/?format=j1&lang=zh', {
      headers: { 'Accept': 'application/json' },
    });
    if (!resp.ok) throw new Error('HTTP ' + resp.status);
    return await resp.json();
  } catch (e) {
    // 备用：wttr.in 纯文本
    try {
      const resp = await fetch('https://wttr.in/?format=%l:+%C,+%t,+%h&lang=zh');
      if (resp.ok) {
        const text = await resp.text();
        return { _textFallback: text };
      }
    } catch {}
    return { error: e.message };
  }
}

// 获取每日一言
async function fetchHitokoto() {
  try {
    const resp = await fetch('https://v1.hitokoto.cn/?c=i&encode=json');
    if (!resp.ok) throw new Error('HTTP ' + resp.status);
    return await resp.json();
  } catch (e) {
    return { error: e.message };
  }
}

// ===== 主调度：服务端 8:00 数据 > 当日缓存 > 实时拉取 =====
let dailyInfo = null;

function localDateStr() {
  const d = new Date();
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}

// 读取服务端每天 8:00 生成的数据
async function loadServerDaily() {
  try {
    const ctrl = new AbortController();
    const timer = setTimeout(() => ctrl.abort(), 5000);
    const resp = await fetch(`daily.json?t=${Date.now()}`, { cache: 'no-store', signal: ctrl.signal });
    clearTimeout(timer);
    if (!resp.ok) return null;
    const data = await resp.json();
    return data.date === localDateStr() ? data : null;
  } catch {
    return null;
  }
}

function applyDaily(info, statusText) {
  dailyInfo = info;
  renderWeather(info.weather);
  renderLunar(info.lunar || computeLunar());
  renderHistory();
  renderHitokoto(info.hitokoto);
  $('dailyStatus').textContent = statusText;
  $('dailyStatus').style.background = 'rgba(0, 206, 201, 0.2)';
  $('dailyStatus').style.color = 'var(--success)';
}

async function refreshHitokoto() {
  $('hitokotoBox').innerHTML = `<div class="di-loading">换一句...</div>`;
  const data = await fetchHitokoto();
  renderHitokoto(data);
  if (dailyInfo && data.hitokoto) {
    dailyInfo.hitokoto = data;
    save(STORAGE_KEYS_EXTRA.DAILY_INFO, dailyInfo);
  }
}

async function initDaily() {
  $('hitokotoRefresh').addEventListener('click', refreshHitokoto);

  // 1. 优先使用服务端每天 8:00 自动抓取的数据
  const serverData = await loadServerDaily();
  if (serverData) {
    const info = { weather: serverData.weather, hitokoto: serverData.hitokoto, lunar: computeLunar() };
    save(STORAGE_KEYS_EXTRA.DAILY_INFO, info);
    localStorage.setItem(STORAGE_KEYS_EXTRA.DAILY_DATE, new Date().toDateString());
    applyDaily(info, '8点数据 ✓');
    return;
  }

  // 2. 当天已有缓存则直接使用
  const today = new Date().toDateString();
  const cachedInfo = load(STORAGE_KEYS_EXTRA.DAILY_INFO, null);
  if (localStorage.getItem(STORAGE_KEYS_EXTRA.DAILY_DATE) === today && cachedInfo) {
    applyDaily(cachedInfo, '今日已缓存 ✓');
    return;
  }

  // 3. 兜底：浏览器直接实时拉取
  $('dailyStatus').textContent = '获取中...';
  const [weather, hitokoto] = await Promise.all([
    fetchWeather().catch(() => ({ error: '网络错误' })),
    fetchHitokoto().catch(() => ({ error: '网络错误' })),
  ]);
  const info = { weather, hitokoto, lunar: computeLunar() };
  save(STORAGE_KEYS_EXTRA.DAILY_INFO, info);
  localStorage.setItem(STORAGE_KEYS_EXTRA.DAILY_DATE, today);
  applyDaily(info, '今日已缓存 ✓');
}

